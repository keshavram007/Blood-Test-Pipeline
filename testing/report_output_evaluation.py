"""
Report output evaluation — scoped to the dashboard's patient-facing view
rather than a separate PDF export (no PDF generation exists in this
pipeline; the dashboard IS the patient-facing deliverable).

Checks:
  1. A patient's report is only reachable in the patient view once
     status == "approved" in the dashboard store.
  2. An approved entry contains the required content: risk classification,
     key biomarker findings, the plain-English narrative, and doctor sign-off
     (reviewing doctor name + approval date).
  3. Simulates the patient-view lookup logic from dashboard.py directly
     against outputs/dashboard_store.json, so this test reflects the exact
     gating condition a real patient would hit, not a re-implementation of it.

Run from the repo root (after having approved at least one patient via the
dashboard, so outputs/dashboard_store.json has real entries to check):
    python testing/report_output_evaluation.py
"""
import sys
import os
import json

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

STORE_PATH = 'outputs/dashboard_store.json'

REQUIRED_APPROVED_FIELDS = ['dob', 'test_date', 'context', 'narrative',
                            'reviewing_doctor', 'approval_date', 'patient_report']


def patient_can_see_report(entry: dict) -> bool:
    """Mirrors the exact gating logic in dashboard.py's PATIENT VIEW section:
    a report is only shown when status == 'approved'. Every other status
    (pending_review, manual_attention, escalated-flagged-but-pending,
    processing_failed) must NOT surface a report to the patient."""
    return entry.get('status') == 'approved'


def evaluate():
    if not os.path.exists(STORE_PATH):
        print(f"No store found at {STORE_PATH}.")
        print("Approve at least one patient through the dashboard first, "
              "then re-run this script.")
        return

    with open(STORE_PATH) as f:
        store = json.load(f)

    if not store:
        print("Store is empty — no patients processed yet.")
        return

    print(f"Loaded {len(store)} patient record(s) from {STORE_PATH}\n")

    n_checked = 0
    n_passed = 0

    for patient_id, entry in store.items():
        status = entry.get('status')
        can_see = patient_can_see_report(entry)

        print(f"{'=' * 70}\nPatient: {patient_id}  |  status: {status}\n{'=' * 70}")

        if status != 'approved':
            # For any non-approved status, the ONLY correct behaviour is
            # that the patient sees nothing report-like.
            ok = not can_see
            print(f"  {'PASS' if ok else 'FAIL'}  "
                  f"non-approved status correctly blocks patient-facing report")
            n_checked += 1
            n_passed += int(ok)
            continue

        # status == 'approved' -> verify full report content requirements
        n_checked += 1
        missing = [field for field in REQUIRED_APPROVED_FIELDS if field not in entry]
        checks = {
            'report reachable by patient (status == approved)': can_see,
            'has risk classification (context.risk_assessment.label)':
                bool(entry.get('context', {}).get('risk_assessment', {}).get('label')),
            'has key biomarker findings (context.biomarker_table)':
                bool(entry.get('context', {}).get('biomarker_table')),
            'has plain-English narrative': bool(entry.get('narrative')),
            'has doctor sign-off (reviewing_doctor)': bool(entry.get('reviewing_doctor')),
            'has approval date': bool(entry.get('approval_date')),
            f'no missing required fields (missing: {missing})': not missing,
        }
        all_ok = all(checks.values())
        for name, ok in checks.items():
            print(f"  {'PASS' if ok else 'FAIL'}  {name}")
        n_passed += int(all_ok)

    print(f"\n{'=' * 70}\nSUMMARY: {n_passed}/{n_checked} patient records passed "
          f"report-output evaluation\n{'=' * 70}")
    print("\nNote: this evaluates the DASHBOARD as the patient-facing deliverable.")
    print("No PDF is generated by this pipeline — the approval-gated dashboard")
    print("view is the report output, and every check above verifies that gate")
    print("and its content requirements directly against real stored records.")


if __name__ == '__main__':
    evaluate()
